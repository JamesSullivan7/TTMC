// Regenerates src/stateCrossings.ts — which states the route passes through,
// and the meter mark at which each is first entered.
//
//   node scripts/state-crossings.mjs
//
// Run this whenever the route in src/config.ts changes. The map tints states
// from this data, so if it goes stale the country lights up in the wrong
// order. src/route.test.ts recomputes it and fails if the committed file no
// longer matches, so a forgotten run is caught rather than shipped.

import fs from 'node:fs'
import { geoContains } from 'd3-geo'
import { feature } from 'topojson-client'

const topo = JSON.parse(fs.readFileSync('node_modules/us-atlas/states-10m.json', 'utf8'))

const src = fs.readFileSync('src/config.ts', 'utf8')
const ms = src.slice(src.indexOf('export const MILESTONES'), src.indexOf('// Route waypoints'))
const ROUTE = [{ m: 0, lat: 36.15, lng: -95.99 }]
for (const m of ms.matchAll(/\{ m: ([0-9_]+), name: '([^']*)',([^}]*)\}/g)) {
  const la = m[3].match(/lat: (-?[\d.]+)/)
  const ln = m[3].match(/lng: (-?[\d.]+)/)
  const kind = (m[3].match(/kind: '(\w+)'/) || [])[1]
  if ((kind === 'city' || kind === 'finish') && la && ln) {
    ROUTE.push({ m: Number(m[1].replace(/_/g, '')), lat: +la[1], lng: +ln[1] })
  }
}
const GOAL = ROUTE[ROUTE.length - 1].m

function positionAt(t) {
  if (t >= GOAL) return ROUTE[ROUTE.length - 1]
  let i = 0
  while (i < ROUTE.length - 1 && ROUTE[i + 1].m <= t) i++
  const a = ROUTE[i]
  const b = ROUTE[Math.min(i + 1, ROUTE.length - 1)]
  const f = b.m > a.m ? (t - a.m) / (b.m - a.m) : 0
  return { lat: a.lat + (b.lat - a.lat) * f, lng: a.lng + (b.lng - a.lng) * f }
}

// Lower 48 only. albersUsa draws AK/HI as insets the route never reaches, and
// ids above 59 are territories.
const states = feature(topo, topo.objects.states).features.filter(
  (f) => f.id !== '02' && f.id !== '15' && Number(f.id) < 60
)

export function computeCrossings(step = 4000) {
  const firstSeen = {}
  let last = null
  for (let m = 0; m <= GOAL; m += step) {
    const p = positionAt(m)
    const pt = [p.lng, p.lat]
    // Whichever state contained us a moment ago almost always still does.
    let hit = last && geoContains(last, pt) ? last : null
    if (!hit) hit = states.find((s) => geoContains(s, pt)) || null
    last = hit
    if (hit && firstSeen[hit.id] === undefined) firstSeen[hit.id] = m
  }
  return Object.entries(firstSeen)
    .sort((a, b) => a[1] - b[1])
    .map(([id, m]) => ({ id, name: states.find((s) => s.id === id).properties.name, m }))
}

// Run the generator only when invoked directly, so the test can import
// computeCrossings without the file rewriting itself. Comparing import.meta.url
// to argv[1] is unreliable on Windows (file://C:/ vs file:///C:/).
const runDirectly = (process.argv[1] || '').replace(/\\/g, '/').endsWith('scripts/state-crossings.mjs')

if (runDirectly) {
  const crossings = computeCrossings()
  const rows = crossings
    .map((c) => `  { id: '${c.id}', name: '${c.name}', m: ${c.m.toLocaleString('en-US').replace(/,/g, '_')} },`)
    .join('\n')

  const out = `// GENERATED by scripts/state-crossings.mjs — do not edit by hand.
// Re-run it whenever the route in config.ts changes:
//
//   node scripts/state-crossings.mjs
//
// Which states the road passes through, and the meter mark at which each is
// first entered. The map fills a state in once the gym reaches it, tinted by
// the act that got them there — so this is what turns the country from a
// backdrop into a record of the journey.
export type StateCrossing = { id: string; name: string; m: number }

export const STATE_CROSSINGS: StateCrossing[] = [
${rows}
]
`
  fs.writeFileSync('src/stateCrossings.ts', out)
  console.log(`wrote src/stateCrossings.ts — ${crossings.length} states`)
  crossings.forEach((c, i) =>
    console.log(
      `  ${String(i + 1).padStart(2)}. ${c.name.padEnd(15)} ${c.m.toLocaleString('en-US').padStart(10)} m`
    )
  )
}
