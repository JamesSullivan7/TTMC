// Writes docs/postcards-needed.md: every postcard still missing, with the exact
// filename to save it as and a ready-made search on each free-to-use stock site.
//
// The wizard (scripts/postcards.sh) walks these one at a time and validates each
// file as it lands. This is the same list as a single page, for when you would
// rather collect all of them in one sitting and run the wizard afterwards to
// wire them in.
//
// Reads the wizard's own WANTED list rather than keeping a second copy, so the
// two cannot drift apart.

import { readFileSync, writeFileSync } from 'node:fs'

const sh = readFileSync('scripts/postcards.sh', 'utf8')
const start = sh.indexOf('WANTED=(')
const block = sh.slice(start, sh.indexOf('\n)', start))

const rows = [...block.matchAll(/"([^"|]+)\|([^|]+)\|([^|]+)\|([^"]*)"/g)].map((m) => ({
  name: m[1],
  file: m[2],
  kind: m[3],
  q: m[4],
}))

if (rows.length === 0) {
  console.error('No WANTED rows parsed — has scripts/postcards.sh changed shape?')
  process.exit(2)
}

const config = readFileSync('src/config.ts', 'utf8')
const todo = rows.filter((r) => !config.includes(`img: '/postcards/${r.file}'`))

// Counted off MILESTONES rather than the WANTED list, which only ever held the
// outstanding ones — "0 of 22 in place" is true of WANTED and meaningless to a
// reader. Sliced to the MILESTONES literal so ROUTE's start-line marker, which
// is a waypoint and not a milestone, does not inflate the total.
const milestones = config.slice(config.indexOf('MILESTONES'), config.indexOf('export const ROUTE'))
const all = [...milestones.matchAll(/\{[^{}]*name:\s*'([^']+)'[^{}]*\}/g)]
const haveCount = all.filter((m) => /img:/.test(m[0])).length

const unsplash = (q) => `https://unsplash.com/s/photos/${encodeURIComponent(q.replace(/ /g, '-'))}`
const pexels = (q) => `https://www.pexels.com/search/${encodeURIComponent(q)}/`
const wikimedia = (q) =>
  `https://commons.wikimedia.org/w/index.php?search=${encodeURIComponent(q)}&ns6=1`

const lines = []
lines.push('# Postcards still needed')
lines.push('')
lines.push(
  `**${todo.length} still needed.** ${haveCount} of the route's ${all.length} milestones already have a photo. Generated by \`node scripts/postcard-manifest.mjs\` — do not hand-edit.`
)
lines.push('')
lines.push('## How to use this')
lines.push('')
lines.push('1. Save each image into `public/postcards/` under the **exact filename** in the table.')
lines.push('2. Run `bash scripts/postcards.sh`. It checks every file is a real JPEG rather than a')
lines.push('   saved error page, and writes the `img:` line into `src/config.ts` for you.')
lines.push('')
lines.push('A milestone with no photo is **not** broken — the celebration falls back to the brand')
lines.push('treatment. So these can land in any order, and partial progress ships fine.')
lines.push('')
lines.push('## What makes a good one')
lines.push('')
lines.push('- **Landscape, and wide.** They are full-bleed backdrops on the gym TV; anything')
lines.push('  portrait gets badly cropped.')
lines.push('- **Dark enough to read white text over.** The celebration puts the milestone name')
lines.push('  across the middle. A bright noon sky is the usual failure.')
lines.push('- **At least ~1600px wide**, and over 20 KB or the wizard will reject it.')
lines.push('')
lines.push('## Licensing — this matters')
lines.push('')
lines.push('These end up on 1080×1080 share cards that members post to Instagram, which is')
lines.push('commercial use of a gym brand. **Unsplash** and **Pexels** are free for that with no')
lines.push('attribution. **Wikimedia Commons** is fine too but the licence varies per image —')
lines.push('check each one. Do not pull from Google Images.')
lines.push('')
lines.push('## The list')
lines.push('')
lines.push('| # | Milestone | Save as | Look for | Search |')
lines.push('|---|---|---|---|---|')

todo.forEach((r, i) => {
  const n = i + 1
  if (r.kind === 'find') {
    const search = `[Unsplash](${unsplash(r.q)}) · [Pexels](${pexels(r.q)}) · [Commons](${wikimedia(r.q)})`
    lines.push(`| ${n} | ${r.name} | \`${r.file}\` | ${r.q} | ${search} |`)
  } else if (r.kind === 'make') {
    lines.push(
      `| ${n} | ${r.name} | \`${r.file}\` | **Make this one.** A number card, not a photo — match \`public/postcards/halfway.jpg\`: big number, brand red \`#D93B58\` on near-black, Anton-ish type | — |`
    )
  } else {
    lines.push(
      `| ${n} | ${r.name} | \`${r.file}\` | **Shoot this one.** The gym and the crew. It fills the screen at 8,473,348 m, the moment the whole month lands — no stock photo can do it | — |`
    )
  }
})

const by = (k) => todo.filter((r) => r.kind === k).length
lines.push('')
lines.push(
  `${by('find')} to find, ${by('make')} to make, ${by('shoot')} to shoot.`
)
lines.push('')

writeFileSync('docs/postcards-needed.md', lines.join('\n'))
console.log(`docs/postcards-needed.md — ${todo.length} outstanding of ${rows.length}`)
